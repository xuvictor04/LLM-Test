"""Model-free check (CPU, operation only) of what a synthetic parent can take as its fifth area, behind register §8
5.3a's limit and 6.1's correction, through DATA's own entry points: open_areas, stream_state, restore_stream_state.

  (1) On the synthetic source every DATA_AREAS entry is generated text, its alphabet the one at its POSITION (alphabet
      4, "789!?.,;:'\\"-()", for a fifth entry): named continual/01_rust, it is that alphabet and not the corpus file.
  (2) A synthetic parent at DATA_SYNTH_HOLDOUT=1 (test 4's) resumed on DATA_SOURCE=real -- the four areas, with
      continual/01_rust appended -- is refused by restore_stream_state: the real blocks are another text.
  (3) At the session's shape (4,725,000 bytes over 5 processes) the parent's record restores, x5 admitted as added.

    python3 synthparent.py                     # synthparent.out

Run it in place, by its path, from any directory but the checkout's root (it finds src/ two folders up)."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or ".") != ROOT]
sys.path.insert(0, os.path.join(ROOT, "src"))
from spine import assemble                                         # noqa: E402
from spine import lever as _lever                                  # noqa: E402
from spine import rng                                              # noqa: E402
from data import api as data_api                                   # noqa: E402

DATA_DIR = os.path.join(ROOT, "data")
X5 = set(b"789!?.,;:'\"-()")


def cfg(**env):
    _lever._reopen_assembly()
    rng.reset_issued()
    e = {"DATA_DIR": DATA_DIR, "DATA_SYNTH_HOLDOUT": "1"}
    e.update({k: str(v) for k, v in env.items()})
    return assemble.build(environ=e)[0]["DATA"]


def areas_of(d, seed=0):
    rng.reset_issued()
    return data_api.open_areas(d, seed=seed)


def refusal(d, areas, state):
    try:
        data_api.restore_stream_state(d, areas, state)
        return None
    except data_api.CorpusError as e:
        return str(e)


FIVE = "eng,py,num,c,continual/01_rust"
parent = cfg(DATA_STREAM_BYTES=3780000)
pstate = data_api.stream_state(parent, areas_of(parent))
print(f"the parent: synthetic, DATA_SYNTH_HOLDOUT=1, 3,780,000 bytes over 4 processes, blocks "
      + ", ".join(f"{a} {r['size']} B" for a, r in pstate["holdout"].items()))

syn5 = cfg(DATA_STREAM_BYTES=4725000, DATA_N_PROCESSES=5, DATA_AREAS=FIVE)
a5 = areas_of(syn5)
name = [n for n in a5.names if n not in ("eng", "py", "num", "c")][0]
body = a5.bodies[name] if isinstance(a5.bodies, dict) else a5.bodies[list(a5.names).index(name)]
rust = b"".join(open(os.path.join(DATA_DIR, "continual", "01_rust", f), "rb").read()
                for f in sorted(os.listdir(os.path.join(DATA_DIR, "continual", "01_rust"))))
print(f"(1) synthetic source, DATA_AREAS={FIVE}: the fifth area '{name}' is {len(body):,} generated bytes, all in "
      f"alphabet 4: {set(body) <= X5}; the corpus file data/continual/01_rust holds {len(rust):,} bytes, "
      f"{len(set(rust))} distinct, of which in alphabet 4: {set(rust) <= X5}")

real5 = cfg(DATA_SOURCE="real", DATA_AREAS=FIVE, DATA_STREAM_BYTES=4725000)
m = refusal(real5, areas_of(real5), pstate)
print(f"(2) the synthetic parent resumed on DATA_SOURCE=real with {FIVE}: "
      + ("RESTORED (unexpected)" if m is None else f"refused -- {m[:400]}"))
real4 = cfg(DATA_SOURCE="real", DATA_STREAM_BYTES=3780000)
m4 = refusal(real4, areas_of(real4), pstate)
print(f"    and on DATA_SOURCE=real with its own four areas at its own length: "
      + ("RESTORED (unexpected)" if m4 is None else f"refused -- {m4[:300]}"))

sess = cfg(DATA_STREAM_BYTES=4725000, DATA_N_PROCESSES=5, DATA_AREAS="eng,py,num,c,x5")
sa = areas_of(sess)
ms = refusal(sess, sa, pstate)
print(f"(3) at the session's shape (eng,py,num,c,x5 at 4,725,000 bytes over 5 processes): "
      + ("restored" if ms is None else f"REFUSED (unexpected) -- {ms[:300]}")
      + f"; data.area_added {sa.counters.get('data.area_added')}; the old blocks the parent's: "
      + str(all(data_api._block_digest(sa.holdout[a]) == pstate['holdout'][a]['digest']
                for a in ("eng", "py", "num", "c"))))
other = cfg(DATA_STREAM_BYTES=3780000, DATA_N_PROCESSES=5, DATA_AREAS="eng,py,num,c,x5")
mo = refusal(other, areas_of(other), pstate)
print(f"    and at the parent's 3,780,000 bytes over 5 processes (756,000 a process): "
      + ("RESTORED (unexpected)" if mo is None else f"refused -- {mo[:300]}"))
